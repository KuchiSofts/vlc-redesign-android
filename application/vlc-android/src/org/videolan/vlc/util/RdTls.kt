    /** the system's roots and Let's Encrypt's together (null: the system's alone, Android 7.1.1 and later) */
    private val factory: SSLSocketFactory? by lazy { if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.N_MR1) null else build() }

    private fun build(): SSLSocketFactory? = try {
        val store = KeyStore.getInstance(KeyStore.getDefaultType()).apply { load(null, null) }
        val system = KeyStore.getInstance("AndroidCAStore").apply { load(null) }
        for (alias in system.aliases()) system.getCertificate(alias)?.let { store.setCertificateEntry(alias, it) }
        val certificates = CertificateFactory.getInstance("X.509")
        ROOTS.forEachIndexed { i, pem -> store.setCertificateEntry("rd-isrg-$i", certificates.generateCertificate(pem.byteInputStream())) }
        val trust = TrustManagerFactory.getInstance(TrustManagerFactory.getDefaultAlgorithm()).apply { init(store) }
        SSLContext.getInstance("TLS").apply { init(null, trust.trustManagers, null) }.socketFactory
    } catch (e: Exception) {
        null
    }

    /** a connection of the app's: Let's Encrypt's roots known on Android 7.0 and before */
    fun apply(connection: URLConnection) {
        if (connection is HttpsURLConnection) factory?.let { connection.sslSocketFactory = it }
    }
}
