#!/usr/bin/env python3
"""Translate the redesign's own strings from the desktop VLC Redesign catalogues.

The Android port reuses the wording of the desktop interface. Its new strings (rd_* in
application/resources/src/main/res/values/redesign_strings.xml) are looked up, by their English text, in the
desktop's po/redesign/<lang>.po and then po/<lang>.po, and written to values-<lang>/redesign_strings.xml for every
language the app already ships. Fuzzy and empty translations are skipped (Android falls back to English).

    import_strings.py [path to the desktop repository]     (default: ../repos/vlc next to this repository)
"""
import os
import re
import sys
import xml.etree.ElementTree as ET

import polib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
RES = os.path.join(ROOT, "application", "resources", "src", "main", "res")
SOURCE = os.path.join(RES, "values", "redesign_strings.xml")

# Android resource folder(s) for a po language code
SPECIAL = {
    "he": ["he", "iw"], "id": ["in", "id"], "es_MX": ["es-rMX"], "pt_BR": ["pt-rBR"], "pt_PT": ["pt"],
    "zh_CN": ["zh-rCN"], "zh_TW": ["zh-rTW"], "nb": ["nb"], "ckb": ["ku"],
}


def android_dirs(lang):
    return SPECIAL.get(lang, [lang.replace("_", "-r")])


def esc(s):
    s = s.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    if s.startswith("@") or s.startswith("?"):
        s = "\\" + s
    return s


def unesc(s):
    return s.replace("\\'", "'").replace('\\"', '"').replace("\\n", "\n").replace("\\\\", "\\")


def load_catalogue(path):
    out = {}
    if not os.path.exists(path):
        return out
    for e in polib.pofile(path):
        if e.obsolete or "fuzzy" in e.flags or not e.msgstr.strip():
            continue
        # the first translation of an English text wins, a context-free one before a context
        if e.msgid not in out or not e.msgctxt:
            out[e.msgid] = e.msgstr
    return out


def main():
    desktop = sys.argv[1] if len(sys.argv) > 1 else os.path.normpath(os.path.join(ROOT, "..", "repos", "vlc"))
    strings = [(n.get("name"), unesc(n.text or "")) for n in ET.parse(SOURCE).getroot()
               if n.tag == "string" and n.get("translatable") != "false"]
    langs = sorted(f[:-3] for f in os.listdir(os.path.join(desktop, "po", "redesign")) if f.endswith(".po"))
    written = 0
    for lang in langs:
        cat = load_catalogue(os.path.join(desktop, "po", lang + ".po"))
        cat.update(load_catalogue(os.path.join(desktop, "po", "redesign", lang + ".po")))
        # Android's %1$s is the desktop's (Qt) %1
        def qt(text):
            return re.sub(r"%(\d)\$[sd]", r"%\1", text)

        def android(text):
            return re.sub(r"%(\d)(?!\$)", r"%\1$s", text)
        rows = [(name, android(cat[qt(text)])) for name, text in strings if qt(text) in cat]
        for d in android_dirs(lang):
            folder = os.path.join(RES, "values-" + d)
            if not os.path.isdir(folder):
                continue
            target = os.path.join(folder, "redesign_strings.xml")
            # a key translated by hand in redesign_strings_android.xml stays there (a second copy would not build)
            own = os.path.join(folder, "redesign_strings_android.xml")
            own = {n.get("name") for n in ET.parse(own).getroot()} if os.path.exists(own) else set()
            kept = [(name, text) for name, text in rows if name not in own]
            if not kept:
                if os.path.exists(target):
                    os.remove(target)
                continue
            with open(target, "w", encoding="utf-8", newline="\n") as f:
                f.write('<?xml version="1.0" encoding="utf-8"?>\n')
                f.write("<!-- Generated by buildsystem/redesign/import_strings.py from the desktop VLC Redesign "
                        "translations. Do not edit. -->\n<resources>\n")
                for name, text in kept:
                    f.write('    <string name="%s">%s</string>\n' % (name, esc(text)))
                f.write("</resources>\n")
            written += 1
            print("%-8s %-10s %d/%d" % (lang, "values-" + d, len(kept), len(strings)))
    print("%d files" % written)


if __name__ == "__main__":
    main()
