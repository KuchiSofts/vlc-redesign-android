#!/usr/bin/env python3
"""The app icon of VLC Redesign for Android, from the designer's vector: Juxtopposed's logo from the VLC Redesign
Figma file (the orange cone, 24 x 24 units, Dark/Accent/Logo #D37918), exported as the desktop repository's
design/icons/svg/logo.svg. The same icon as the desktop's (share/icons/scalable/vlc.svg there).

    python buildsystem/redesign/make_app_icon.py [<path to the desktop repository's design folder>]

Writes:
  application/resources/src/main/res/drawable/ic_launcher_{background,foreground,monochrome}.xml
        the adaptive icon (Android 8+): the design's background #0E0E0E (Dark/BG/B1, the window the designer shows
        the logo on), the logo at 2.2 x in the middle of the 108 dp layer (46 dp tall, inside the 66 dp safe
        circle), and the same logo as the monochrome layer of themed icons (Android 13+)
  application/vlc-android/res/mipmap-anydpi-v26/ic_launcher_round.xml   (the round icon: the same layers)
  application/vlc-android/res/mipmap-{mdpi..xxxhdpi}/ic_launcher.png, ic_launcher_round.png
        Android 7.1 and older: the adaptive icon as the launcher shows it (rounded square, circle), 48 to 192 px
  application/app/src/main/ic_launcher-playstore.png   the Play Store icon, 512 x 512, full bleed (the store masks it)
  application/resources/src/main/res/drawable-{ldpi..xxxhdpi}/icon.png   the logo alone (android:logo, MainActivity)
  application/resources/src/main/res/drawable-{ldpi..xhdpi}/banner.png  the TV banner: the logo and "VLC" in Inter
  application/resources/assets/images/svg/ic_launcher*.svg   the sources of the launcher icon, as SVG (the banner's
        old source banner.svg is removed: the banner is drawn here)
and removes the debug build's own launcher layers and banners (the debug app has the same icon).

The notification icon (drawable/ic_stat_vlc.xml, the logo in white) is written by import_design.py.
Needs Pillow and resvg-py (pip install pillow resvg-py).
"""
import io, os, re, sys

import resvg_py
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
APP = os.path.join(ROOT, "application")
RES = os.path.join(APP, "resources", "src", "main", "res")
MIPMAP = os.path.join(APP, "vlc-android", "res")
SVGS = os.path.join(APP, "resources", "assets", "images", "svg")

BACKGROUND = "#0E0E0E"      # Dark/BG/B1
LOGO_COLOUR = "#D37918"     # Dark/Accent/Logo
TEXT_COLOUR = (237, 237, 237, 255)
SCALE = 2.2                 # the 24-unit logo in the 108 dp layer
CENTRE = 12                 # the logo's box (3..21 x 1.5..22.5) is centred in its 24-unit frame
LEGACY = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
ICON = {"ldpi": 64, "mdpi": 96, "hdpi": 144, "xhdpi": 192, "xxhdpi": 288, "xxxhdpi": 384}
BANNER = {"ldpi": (213, 117), "mdpi": (320, 176), "hdpi": (480, 264), "xhdpi": (640, 352)}
HEADER = ("<!-- Generated by buildsystem/redesign/make_app_icon.py from the VLC Redesign design folder: Juxtopposed's "
          "logo (icons/svg/logo.svg), the desktop's app icon. Do not edit. -->\n")


def paths(design):
    svg = open(os.path.join(design, "icons", "svg", "logo.svg"), encoding="utf-8").read()
    return [d for d, _ in re.findall(r'<path\b[^>]*?\bd="([^"]+)"[^>]*?\bfill="([^"]+)"', svg)]


def fmt(v):
    return ("%.4f" % v).rstrip("0").rstrip(".")


def write(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    mode = "wb" if isinstance(data, bytes) else "w"
    with open(path, mode, **({} if mode == "wb" else {"encoding": "utf-8", "newline": "\n"})) as f:
        f.write(data)
    print("wrote", os.path.relpath(path, ROOT))


def remove(path):
    if os.path.exists(path):
        os.remove(path)
        print("removed", os.path.relpath(path, ROOT))


# --- vectors ------------------------------------------------------------------------------------------------------

def layer_xml(ds, fill):
    t = 54 - CENTRE * SCALE
    out = ['<?xml version="1.0" encoding="utf-8"?>', HEADER.rstrip("\n"),
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">',
           '    <group android:translateX="%s" android:translateY="%s" android:scaleX="%s" android:scaleY="%s">'
           % (fmt(t), fmt(t), fmt(SCALE), fmt(SCALE))]
    out += ['        <path android:pathData="%s" android:fillColor="%s" />' % (d, fill) for d in ds]
    out += ["    </group>", "</vector>", ""]
    return "\n".join(out)


def background_xml():
    return "\n".join(['<?xml version="1.0" encoding="utf-8"?>', HEADER.rstrip("\n"),
                      '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
                      '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">',
                      '    <path android:pathData="M0,0h108v108h-108z" android:fillColor="#FF%s" />' % BACKGROUND[1:],
                      "</vector>", ""])


def svg_layer(ds, fill, background=None, view=(0, 0, 108, 108)):
    t = 54 - CENTRE * SCALE
    out = ['<svg width="%s" height="%s" viewBox="%s" fill="none" xmlns="http://www.w3.org/2000/svg">'
           % (fmt(view[2]), fmt(view[3]), " ".join(fmt(v) for v in view))]
    if background:
        out.append('<rect x="0" y="0" width="108" height="108" fill="%s"/>' % background)
    out.append('<g transform="translate(%s %s) scale(%s)">' % (fmt(t), fmt(t), fmt(SCALE)))
    out += ['<path d="%s" fill="%s"/>' % (d, fill) for d in ds]
    out += ["</g>", "</svg>", ""]
    return "\n".join(out)


def svg_logo(ds, size=24):
    return "\n".join(['<svg width="%d" height="%d" viewBox="0 0 24 24" fill="none" xmlns="http://www.w3.org/2000/svg">'
                      % (size, size)] + ['<path d="%s" fill="%s"/>' % (d, LOGO_COLOUR) for d in ds] + ["</svg>", ""])


def render(svg, w, h=None):
    data = bytes(resvg_py.svg_to_bytes(svg_string=svg, width=w, height=h or w))
    return Image.open(io.BytesIO(data)).convert("RGBA")


def png(img):
    out = io.BytesIO()
    img.save(out, "PNG", optimize=True)
    return out.getvalue()


def masked(full, shape):
    """The visible 72 dp of the 108 dp icon, in the launcher's shape, drawn 4x and scaled down"""
    size = full.size[0]
    ss = 4
    mask = Image.new("L", (size * ss, size * ss), 0)
    d = ImageDraw.Draw(mask)
    if shape == "round":
        d.ellipse((0, 0, size * ss - 1, size * ss - 1), fill=255)
    else:
        d.rounded_rectangle((0, 0, size * ss - 1, size * ss - 1), radius=size * ss * 0.22, fill=255)
    mask = mask.resize((size, size), Image.LANCZOS)
    out = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    out.paste(full, (0, 0), mask)
    return out


def banner(ds, w, h, font_path):
    img = Image.new("RGBA", (w, h), (14, 14, 14, 255))
    logo_h = round(h * 0.70)
    logo = render(svg_logo(ds, logo_h), logo_h)
    gap = w * 0.06
    font = ImageFont.truetype(font_path, round(h * 0.30))
    try:
        font.set_variation_by_name("Medium")
    except Exception:
        pass
    text = "VLC"
    box = ImageDraw.Draw(img).textbbox((0, 0), text, font=font)
    tw, th = box[2] - box[0], box[3] - box[1]
    total = logo_h + gap + tw
    x0 = (w - total) / 2
    img.alpha_composite(logo, (round(x0), round((h - logo_h) / 2)))
    ImageDraw.Draw(img).text((x0 + logo_h + gap - box[0], (h - th) / 2 - box[1]), text, font=font, fill=TEXT_COLOUR)
    return img


def main():
    design = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.expanduser("~"), "source", "repos", "vlc", "design")
    ds = paths(design)
    draw = os.path.join(RES, "drawable")
    write(os.path.join(draw, "ic_launcher_background.xml"), background_xml())
    write(os.path.join(draw, "ic_launcher_foreground.xml"), layer_xml(ds, "#FF" + LOGO_COLOUR[1:]))
    write(os.path.join(draw, "ic_launcher_monochrome.xml"), layer_xml(ds, "#FF000000"))
    adaptive = open(os.path.join(MIPMAP, "mipmap-anydpi-v26", "ic_launcher.xml"), encoding="utf-8").read()
    write(os.path.join(MIPMAP, "mipmap-anydpi-v26", "ic_launcher_round.xml"), adaptive)

    full_svg = svg_layer(ds, LOGO_COLOUR, BACKGROUND)
    visible = full_svg.replace('viewBox="0 0 108 108"', 'viewBox="18 18 72 72"')
    for density, px in LEGACY.items():
        full = render(visible, px * 2).resize((px, px), Image.LANCZOS)
        write(os.path.join(MIPMAP, "mipmap-" + density, "ic_launcher.png"), png(masked(full, "square")))
        write(os.path.join(MIPMAP, "mipmap-" + density, "ic_launcher_round.png"), png(masked(full, "round")))
    write(os.path.join(APP, "app", "src", "main", "ic_launcher-playstore.png"), png(render(visible, 512)))
    for density, px in ICON.items():
        write(os.path.join(RES, "drawable-" + density, "icon.png"), png(render(svg_logo(ds, px), px)))
    font = os.path.join(RES, "font", "inter_variable.ttf")
    for density, (w, h) in BANNER.items():
        write(os.path.join(RES, "drawable-" + density, "banner.png"), png(banner(ds, w, h, font)))

    # the sources, as SVG
    write(os.path.join(SVGS, "ic_launcher_background.svg"),
          '<svg width="108" height="108" viewBox="0 0 108 108" xmlns="http://www.w3.org/2000/svg">\n'
          '<rect width="108" height="108" fill="%s"/>\n</svg>\n' % BACKGROUND)
    write(os.path.join(SVGS, "ic_launcher_foreground.svg"), svg_layer(ds, LOGO_COLOUR))
    write(os.path.join(SVGS, "ic_launcher_monochrome.svg"), svg_layer(ds, "#000000"))
    write(os.path.join(SVGS, "ic_launcher.svg"), full_svg)
    for name in ("ic_launcher_debug.svg", "ic_launcher_background_debug.svg", "ic_launcher_foreground_debug.svg",
                 "banner_debug.svg", "banner.svg"):
        remove(os.path.join(SVGS, name))
    # previews of the old icon
    prev = os.path.join(SVGS, "ic_launcher_preview")
    for kind in ("debug", "source"):
        for shape in ("circle", "square", "squircle"):
            remove(os.path.join(prev, "ic_launcher_%s_%s.svg" % (kind, shape)))
    # the debug build: the same icon and banner
    for name in ("ic_launcher_background.xml", "ic_launcher_foreground.xml"):
        remove(os.path.join(APP, "resources", "flavors", "debug", "res", "drawable", name))
    for density in BANNER:
        remove(os.path.join(APP, "vlc-android", "flavors", "debug", "res", "drawable-" + density, "banner.png"))
    print("done")


if __name__ == "__main__":
    main()
