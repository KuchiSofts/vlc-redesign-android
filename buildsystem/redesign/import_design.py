def fmt(v):
    s = ("%.4f" % v).rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def rect_path(x, y, w, h, rx, ry):
    if rx <= 0 and ry <= 0:
        return "M%s,%sh%sv%sh%sz" % (fmt(x), fmt(y), fmt(w), fmt(h), fmt(-w))
    rx = min(rx or ry, w / 2)
    ry = min(ry or rx, h / 2)
    return ("M%s,%sh%sa%s,%s 0,0 1,%s,%sv%sa%s,%s 0,0 1,%s,%sh%sa%s,%s 0,0 1,%s,%sv%sa%s,%s 0,0 1,%s,%sz" % (
        fmt(x + rx), fmt(y), fmt(w - 2 * rx), fmt(rx), fmt(ry), fmt(rx), fmt(ry), fmt(h - 2 * ry), fmt(rx), fmt(ry),
        fmt(-rx), fmt(ry), fmt(-(w - 2 * rx)), fmt(rx), fmt(ry), fmt(-rx), fmt(-ry), fmt(-(h - 2 * ry)), fmt(rx),
        fmt(ry), fmt(rx), fmt(-ry)))


def ellipse_path(cx, cy, rx, ry):
    return "M%s,%sa%s,%s 0,1 1,%s,0a%s,%s 0,1 1,%s,0z" % (
        fmt(cx - rx), fmt(cy), fmt(rx), fmt(ry), fmt(2 * rx), fmt(rx), fmt(ry), fmt(-2 * rx))


def parse_transform(tr):
    """Return (translateX, translateY, scaleX, scaleY, rotation) for translate()/matrix() without skew."""
    if not tr:
        return None
    m = re.match(r"\s*translate\(\s*([-\d.e]+)[ ,]*([-\d.e]*)\s*\)", tr)
    if m:
        return float(m.group(1)), float(m.group(2) or 0), 1.0, 1.0, 0.0
    m = re.match(r"\s*matrix\(([^)]*)\)", tr)
    if m:
        a, b, c, d, e, f = [float(v) for v in re.split(r"[ ,]+", m.group(1).strip())]
        sx = math.hypot(a, b)
        th = math.atan2(b, a)
        sy = -c * math.sin(th) + d * math.cos(th)
        return e, f, sx, sy, math.degrees(th)
    raise ValueError("transform " + tr)


def color_of(v, missing):
    if v is None or v == "none":
        return None
    if v.startswith("url("):
        return None
    u = {"BLACK": "#000000", "WHITE": "#FFFFFF"}.get(v.upper(), v.upper())
    if u in SVG_COLORS:
        return SVG_COLORS[u]
    missing.add(u)
    return argb(u)


def shape_path(el):
    tag = el.tag.split("}")[-1]
    g = lambda k, d=0.0: float(el.get(k, d))
    if tag == "path":
        return el.get("d")
    if tag == "rect":
        return rect_path(g("x"), g("y"), g("width"), g("height"), g("rx", el.get("ry", 0)), g("ry", el.get("rx", 0)))
    if tag == "circle":
        return ellipse_path(g("cx"), g("cy"), g("r"), g("r"))
    if tag == "ellipse":
        return ellipse_path(g("cx"), g("cy"), g("rx"), g("ry"))
    if tag == "line":
        return "M%s,%sL%s,%s" % (fmt(g("x1")), fmt(g("y1")), fmt(g("x2")), fmt(g("y2")))
    if tag in ("polyline", "polygon"):
        pts = re.split(r"[ ,]+", el.get("points").strip())
        d = "M" + " ".join("%s,%s" % (pts[i], pts[i + 1]) for i in range(0, len(pts), 2))
        return d + ("z" if tag == "polygon" else "")
    return None


def convert(svg_file, colour_map=None, size=None):
    tree = ET.parse(svg_file)
    root = tree.getroot()
    vb = [float(v) for v in root.get("viewBox").split()]
    w, h = float(root.get("width", vb[2])), float(root.get("height", vb[3]))
    missing = set()
    out = []

    def attrs(el, inherited):
        a = dict(inherited)
        for k in ("fill", "stroke", "stroke-width", "stroke-linecap", "stroke-linejoin", "fill-rule", "opacity",
                  "fill-opacity", "stroke-opacity"):
            if el.get(k) is not None:
                a[k] = el.get(k)
        return a

    def walk(el, inherited, indent):
        for ch in el:
            tag = ch.tag.split("}")[-1]
            if tag in ("defs", "title", "desc", "linearGradient", "radialGradient", "clipPath", "mask"):
                continue
            a = attrs(ch, inherited)
            tr = parse_transform(ch.get("transform"))
            pad = "    " * indent
            if tr:
                out.append('%s<group android:translateX="%s" android:translateY="%s" android:scaleX="%s" android:scaleY="%s" android:rotation="%s">'
                           % (pad, fmt(tr[0]), fmt(tr[1]), fmt(tr[2]), fmt(tr[3]), fmt(tr[4])))
                indent += 1
                pad = "    " * indent
            if tag == "g":
                walk(ch, a, indent)
            else:
                d = shape_path(ch)
                if d:
                    fill = color_of(a.get("fill", "#000000"), missing)
                    stroke = color_of(a.get("stroke"), missing)
                    if colour_map:
                        fill = colour_map.get(fill, fill)
                        stroke = colour_map.get(stroke, stroke)
                    if not fill and not stroke:
                        continue
                    p = ['%s<path android:pathData="%s"' % (pad, re.sub(r"\s+", " ", d.strip()))]
                    if fill:
                        p.append('android:fillColor="%s"' % fill)
                        if a.get("fill-rule") == "evenodd":
                            p.append('android:fillType="evenOdd"')
                    if stroke:
                        p.append('android:strokeColor="%s" android:strokeWidth="%s"' % (stroke, fmt(float(a.get("stroke-width", 1)))))
                        if a.get("stroke-linecap"):
                            p.append('android:strokeLineCap="%s"' % a["stroke-linecap"])
                        if a.get("stroke-linejoin"):
                            p.append('android:strokeLineJoin="%s"' % a["stroke-linejoin"])
                    op = float(a.get("opacity", 1))
                    if op != 1:
                        if fill:
                            p.append('android:fillAlpha="%s"' % fmt(op * float(a.get("fill-opacity", 1))))
                        if stroke:
                            p.append('android:strokeAlpha="%s"' % fmt(op * float(a.get("stroke-opacity", 1))))
                    out.append(" ".join(p) + " />")
            if tr:
                indent -= 1
                out.append("    " * indent + "</group>")

    walk(root, attrs(root, {}), 1)
    body = ('<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="%sdp" android:height="%sdp" android:viewportWidth="%s" android:viewportHeight="%s">\n'
            % (fmt(size or w), fmt(size or h), fmt(vb[2]), fmt(vb[3])))
    if vb[0] or vb[1]:
        out.insert(0, '    <group android:translateX="%s" android:translateY="%s">' % (fmt(-vb[0]), fmt(-vb[1])))
        out.append("    </group>")
    return body + "\n".join(out) + "\n</vector>\n", missing


HAND_DRAWN = {"rd_ic_chevron_right.xml", "rd_ic_mini_pause.xml", "rd_ic_mini_play.xml", "rd_ic_player_bar_settings.xml", "rd_ic_phone.xml"}


def icons(design, version):
    ddir = os.path.join(RES, "drawable")
    for f in os.listdir(ddir):
        # drawn by hand for Android (not in design/): kept
        if f.startswith("rd_ic_") and f.endswith(".xml") and f not in HAND_DRAWN:
            os.remove(os.path.join(ddir, f))
    hdr = '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER % version
    count = 0
    for sub, prefix in (("svg", "rd_ic_"), (os.path.join("svg", "duo"), "rd_ic_duo_")):
        folder = os.path.join(design, "icons", sub)
        for f in sorted(os.listdir(folder)):
            if not f.endswith(".svg"):
                continue
            name = prefix + re.sub(r"[^a-z0-9]+", "_", f[:-4].lower()).strip("_")
            xml, missing = convert(os.path.join(folder, f))
            if missing:
                print("  %s: literal colours %s" % (f, ", ".join(sorted(missing))))
            write(os.path.join(ddir, name + ".xml"), hdr + xml)
            count += 1
    for name in EXTRA:
        write(os.path.join(ddir, "rd_ic_%s.xml" % name), hdr + extra_xml(name, "@color/rd_fg_a2"))
        count += 1
    # The active (accent) state of the single-colour icons, as the desktop sidebar and player draw them.
    folder = os.path.join(design, "icons", "svg")
    for n in ACTIVE_VARIANTS:
        xml, _ = convert(os.path.join(folder, n + ".svg"), {"@color/rd_fg_a2": "?attr/colorPrimary", "@color/rd_fg_a3": "?attr/colorPrimary"})
        write(os.path.join(ddir, "rd_ic_%s_active.xml" % n.replace("-", "_")), hdr + xml)
        count += 1
    print("icons:", count)


