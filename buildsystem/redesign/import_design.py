def token(t, path):
    node = t
    for p in path.split("."):
        node = node[p]
    return node["$value"]


def argb(hexc):
    h = hexc.lstrip("#").upper()
    if len(h) == 6:
        return "#FF" + h
    if len(h) == 8:  # #RRGGBBAA
        return "#" + h[6:] + h[:6]
    raise ValueError(hexc)


