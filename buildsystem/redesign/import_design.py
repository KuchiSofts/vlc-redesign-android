def write(path, text):
    if os.path.basename(path) in AUTO_MIRRORED and "autoMirrored" not in text:
        text = re.sub(r'(android:viewportHeight="[^"]*")>', r'\1' + '\n    android:autoMirrored="true">', text, count=1)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def colors(t, version):
    day, night = [], []
    fixed = []
    for name, p in THEME.items():
        d, l = token(t, "color.dark." + p), token(t, "color.light." + p)
        fixed.append('    <color name="rd_dark_%s">%s</color>' % (name, argb(d)))
        fixed.append('    <color name="rd_light_%s">%s</color>' % (name, argb(l)))
        day.append('    <color name="rd_%s">@color/rd_light_%s</color>' % (name, name))
        night.append('    <color name="rd_%s">@color/rd_dark_%s</color>' % (name, name))
    acc = t["accent"]["choice"]
    for a in acc:
        if a.startswith("$"):
            continue
        for k in ("main", "dim", "bright", "brightLight"):
            fixed.append('    <color name="rd_accent_%s_%s">%s</color>' % (a, re.sub("([A-Z])", r"_\1", k).lower(), argb(acc[a][k]["$value"])))
    fixed.append('    <color name="rd_logo">%s</color>' % argb(token(t, "accent.logo")))
    # The default accent (orange): in the dark theme Bright is the dark tint, in the light theme the light one.
    day += ['    <color name="rd_accent">@color/rd_accent_orange_main</color>',
            '    <color name="rd_accent_dim">@color/rd_accent_orange_dim</color>',
            '    <color name="rd_accent_bright">@color/rd_accent_orange_bright_light</color>']
    night += ['    <color name="rd_accent">@color/rd_accent_orange_main</color>',
              '    <color name="rd_accent_dim">@color/rd_accent_orange_dim</color>',
              '    <color name="rd_accent_bright">@color/rd_accent_orange_bright</color>']
    hdr = '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER % version
    write(os.path.join(RES, "values", "redesign_colors.xml"),
          hdr + "<resources>\n" + "\n".join(fixed + day) + "\n</resources>\n")
    write(os.path.join(RES, "values-night", "redesign_colors.xml"),
          hdr + "<resources>\n" + "\n".join(night) + "\n</resources>\n")


